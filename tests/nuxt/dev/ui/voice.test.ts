import { afterEach, beforeEach, expect, it, vi } from 'vitest'

import { resetVoiceScenario, setVoiceScenario, useVoice, useVoiceLive, voiceChannelOf, voiceDisplayMembers, voiceMembers, watchersOf } from '~~/dev/ui/voice'

beforeEach(() => resetVoiceScenario('populated'))
afterEach(() => {
  vi.unstubAllGlobals()
  vi.restoreAllMocks()
})

it('shares deterministic presence, watch state, and local mute/media controls without device access', async () => {
  const capture = vi.fn()
  vi.stubGlobal('navigator', { mediaDevices: { getUserMedia: capture, getDisplayMedia: capture, enumerateDevices: capture } })
  const v = useVoice()
  useVoiceLive()
  expect(voiceMembers('ui-voice').map(m => m.userId)).toEqual(['ui-me', 'ui-alex', 'ui-sam', 'ui-jordan'])
  expect(voiceChannelOf('ui-me')).toBe('ui-voice')
  expect(watchersOf('ui-alex')).toEqual(['ui-me', 'ui-sam'])
  expect(v.tiles.value.find(t => t.userId === 'ui-alex')?.screen).toBeDefined()
  v.watch('ui-alex', false)
  expect(v.tiles.value.find(t => t.userId === 'ui-alex')?.screen).toBeUndefined()
  v.watch('ui-sam', true)
  expect(v.theater.value).toBe('ui-sam')
  expect(v.tiles.value.find(t => t.userId === 'ui-sam')?.cam).toBeDefined()
  v.toggleHeadphones()
  expect(v.mute.value).toMatchObject({ muted: true, deafened: true })
  v.toggleMic()
  expect(v.mute.value).toMatchObject({ muted: false, deafened: false })
  await v.toggleCamera()
  await v.startScreen()
  await v.setScreenAudio(false)
  await v.setScreenQuality({ height: 720, fps: 30 })
  expect(v.tiles.value[0]).toMatchObject({ local: true, camLive: true, screenLive: true, screenAudio: false, screenQuality: { height: 720, fps: 30 } })
  v.setRadioListening(true)
  v.setVolume('ui-alex', { screen: 0.3 })
  expect(voiceMembers('ui-voice')[0]?.radioListening).toBe(true)
  expect(v.volumes.value['ui-alex']?.screen).toBe(0.3)
  await v.stopScreen()
  await v.leave()
  expect(v.tiles.value).toEqual([])
  expect(v.camOn.value).toBe(false)
  expect(voiceChannelOf('ui-me')).toBeNull()
  expect(voiceChannelOf('ui-alex')).toBe('ui-voice')
  expect(capture).not.toHaveBeenCalled()
})

it('resets all presets and recovers from simulated errors and reconnects', async () => {
  const v = useVoice()
  resetVoiceScenario('connecting')
  expect(v.connectionLabel.value).toBe('Connecting…')
  expect(v.channelId.value).toBeNull()
  expect(v.pendingChannelId.value).toBe('ui-voice')
  expect(voiceDisplayMembers('ui-voice', 'ui-me')).toContainEqual(expect.objectContaining({ userId: 'ui-me', pending: true }))
  await v.leave()
  expect(v.connecting.value).toBe(false)
  expect(v.pendingChannelId.value).toBeNull()
  resetVoiceScenario('errors')
  expect(v.audioBlocked.value).toBe(true)
  expect(v.microphone.value).toBe('unavailable')
  await v.enableAudio()
  await v.enableMicrophone()
  expect(v.connectionLabel.value).toBe('Connected')
  resetVoiceScenario('reconnecting')
  expect(v.connectionLabel.value).toBe('Reconnecting…')
  expect(v.ping.value).toBeNull()
  await v.reconnect()
  expect(v.connection.value).toBe('connected')
  setVoiceScenario({ speaking: ['ui-sam'], playing: { 'ui-sam': 'i-lucide-music' }, connection: 'signalReconnecting' })
  expect(v.tiles.value.find(t => t.userId === 'ui-sam')?.speaking).toBe(true)
  expect(v.playing.value['ui-sam']).toBe('i-lucide-music')
  resetVoiceScenario('empty')
  expect(v.connection.value).toBe('disconnected')
  expect(voiceMembers('ui-voice')).toEqual([])
  expect(v.playing.value).toEqual({})
  await v.join('ui-voice')
  expect(voiceDisplayMembers('ui-voice', 'ui-me')).toMatchObject([{ userId: 'ui-me', pending: false }])
  await v.move('another-channel')
  expect(voiceChannelOf('ui-me')).toBe('another-channel')
  resetVoiceScenario('populated')
  expect(v.watching.value).toEqual(['ui-alex'])
  expect(v.screenOn.value).toBe(false)
})

it('creates canvas tracks only on attachment and stops them on detach and reset', () => {
  const stop = vi.fn()
  const stream = Object.assign(new MediaStream(), { getTracks: () => [{ stop } as unknown as MediaStreamTrack] })
  const capture = vi.fn(() => stream)
  const context = { fillRect: vi.fn(), fillText: vi.fn(), beginPath: vi.fn(), arc: vi.fn(), fill: vi.fn() }
  vi.spyOn(HTMLCanvasElement.prototype, 'getContext').mockReturnValue(context as unknown as CanvasRenderingContext2D)
  Object.defineProperty(HTMLCanvasElement.prototype, 'captureStream', { configurable: true, value: capture })
  try {
    const v = useVoice()
    const track = v.tiles.value.find(t => t.userId === 'ui-alex')!.cam!
    expect(capture).not.toHaveBeenCalled()
    const element = document.createElement('video')
    track.attach(element)
    expect(element.srcObject).toBe(stream)
    track.detach(element)
    expect(element.srcObject).toBeNull()
    expect(stop).toHaveBeenCalledTimes(1)
    track.attach(element)
    resetVoiceScenario('empty')
    expect(element.srcObject).toBeNull()
    expect(stop).toHaveBeenCalledTimes(2)
  } finally {
    Reflect.deleteProperty(HTMLCanvasElement.prototype, 'captureStream')
    vi.restoreAllMocks()
  }
})
